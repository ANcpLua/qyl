using System;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Qyl.Sdk.Xml.Generator;

/// <summary>Writes the partial type that implements <c>Qyl.Xml.IXmlWritable</c> for an <see cref="XmlModelSpec"/>.</summary>
internal static class XmlWriterEmitter
{
    public static string Emit(XmlModelSpec spec)
    {
        var source = new StringBuilder();
        var indent = spec.Namespace is null ? string.Empty : "    ";

        source.AppendLine("// <auto-generated/>");
        source.AppendLine("// Generated by Qyl.Sdk.Xml.Generator for [GenerateXml]. Do not edit; change the model instead.");
        source.AppendLine("#nullable enable");
        source.AppendLine();

        if (spec.Namespace is not null)
        {
            source.Append("namespace ").AppendLine(spec.Namespace);
            source.AppendLine("{");
        }

        source.Append(indent).Append("partial ").Append(spec.TypeKeyword).Append(' ').Append(spec.TypeName)
            .AppendLine(" : global::Qyl.Xml.IXmlWritable");
        source.Append(indent).AppendLine("{");
        source.Append(indent).AppendLine("    /// <inheritdoc />");
        source.Append(indent).AppendLine("    public void WriteXml(global::System.Xml.XmlWriter writer)");
        source.Append(indent).AppendLine("    {");
        source.Append(indent).AppendLine("        global::System.ArgumentNullException.ThrowIfNull(writer);");
        source.AppendLine();

        var body = indent + "        ";
        AppendStartElement(source, body, spec.RootName, spec.RootNamespace);

        // XmlWriter requires attributes before any child content.
        for (var index = 0; index < spec.Properties.Count; index++)
        {
            if (spec.Properties[index].IsAttribute)
            {
                AppendProperty(source, body, spec.Properties[index], index);
            }
        }

        for (var index = 0; index < spec.Properties.Count; index++)
        {
            if (!spec.Properties[index].IsAttribute)
            {
                AppendProperty(source, body, spec.Properties[index], index);
            }
        }

        source.Append(body).AppendLine("writer.WriteEndElement();");
        source.Append(indent).AppendLine("    }");
        source.Append(indent).AppendLine("}");

        if (spec.Namespace is not null)
        {
            source.AppendLine("}");
        }

        return source.ToString();
    }

    private static void AppendProperty(StringBuilder source, string indent, XmlPropertySpec property, int index)
    {
        var local = "value" + index.ToString(CultureInfo.InvariantCulture);
        source.Append(indent).Append("var ").Append(local).Append(" = this.").Append(EscapeIdentifier(property.PropertyName)).AppendLine(";");

        if (property.IsNullable)
        {
            var condition = property.Kind == ValueKind.String ? local + " is not null" : local + ".HasValue";
            source.Append(indent).Append("if (").Append(condition).AppendLine(")");
            source.Append(indent).AppendLine("{");
            AppendPropertyValue(source, indent + "    ", property, local);
            source.Append(indent).AppendLine("}");
        }
        else
        {
            AppendPropertyValue(source, indent, property, local);
        }
    }

    private static void AppendPropertyValue(StringBuilder source, string indent, XmlPropertySpec property, string local)
    {
        var valueExpression = property.IsNullable && property.Kind != ValueKind.String ? local + ".Value" : local;
        var formatted = Format(valueExpression, property.Kind);

        if (property.IsAttribute)
        {
            source.Append(indent).Append("writer.WriteAttributeString(");
            if (string.IsNullOrEmpty(property.XmlNamespace))
            {
                source.Append(Literal(property.XmlName)).Append(", ");
            }
            else
            {
                source.Append("null, ").Append(Literal(property.XmlName)).Append(", ").Append(Literal(property.XmlNamespace!)).Append(", ");
            }

            source.Append(formatted).AppendLine(");");
            return;
        }

        AppendStartElement(source, indent, property.XmlName, property.XmlNamespace);
        source.Append(indent).Append("writer.WriteString(").Append(formatted).AppendLine(");");
        source.Append(indent).AppendLine("writer.WriteEndElement();");
    }

    private static string Format(string valueExpression, ValueKind kind)
    {
        return kind switch
        {
            ValueKind.String => valueExpression,
            ValueKind.DateTime => "global::System.Xml.XmlConvert.ToString(" + valueExpression + ", global::System.Xml.XmlDateTimeSerializationMode.RoundtripKind)",
            ValueKind.DateOnly or ValueKind.TimeOnly => valueExpression + ".ToString(\"O\", global::System.Globalization.CultureInfo.InvariantCulture)",
            ValueKind.Enum => valueExpression + ".ToString()",
            ValueKind.XmlConvertScalar or ValueKind.DateTimeOffset or ValueKind.Guid or ValueKind.TimeSpan =>
                "global::System.Xml.XmlConvert.ToString(" + valueExpression + ")",
            _ => throw new InvalidOperationException("Unknown XML scalar kind."),
        };
    }

    private static void AppendStartElement(StringBuilder source, string indent, string name, string? xmlNamespace)
    {
        source.Append(indent).Append("writer.WriteStartElement(");
        if (string.IsNullOrEmpty(xmlNamespace))
        {
            source.Append(Literal(name));
        }
        else
        {
            source.Append("null, ").Append(Literal(name)).Append(", ").Append(Literal(xmlNamespace!));
        }

        source.AppendLine(");");
    }

    private static string Literal(string value) => SymbolDisplay.FormatLiteral(value, quote: true);

    private static string EscapeIdentifier(string identifier)
    {
        return SyntaxFacts.GetKeywordKind(identifier) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(identifier) != SyntaxKind.None
            ? "@" + identifier
            : identifier;
    }
}
